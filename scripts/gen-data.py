#!/usr/bin/env python3
"""Generates Grandmaster Lab's static chess data (run once; outputs are committed).

  python scripts/gen-data.py

Requires python-chess (pip install chess).

Outputs
  src/workers/book/polyglot-random.ts  Polyglot Random64 table as hi/lo uint32 pairs
  public/books/eco.json                 opening names keyed by Polyglot hash
                                        (source: lichess-org/chess-openings, CC0)
  scripts/polyglot-vectors.json         random games + expected keys for tests
"""

import json
import random
from pathlib import Path

import chess
import chess.polyglot

ROOT = Path(__file__).resolve().parent.parent


def write_random_table() -> None:
    values = chess.polyglot.POLYGLOT_RANDOM_ARRAY
    assert len(values) == 781
    words = []
    for v in values:
        words.append(f"0x{(v >> 32) & 0xFFFFFFFF:08x}")
        words.append(f"0x{v & 0xFFFFFFFF:08x}")
    rows = [", ".join(words[i : i + 8]) for i in range(0, len(words), 8)]
    body = ",\n  ".join(rows)
    out = ROOT / "src/workers/book/polyglot-random.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by scripts/gen-data.py from python-chess. Do not edit.\n"
        "// Polyglot Random64[781], stored as [hi0, lo0, hi1, lo1, ...].\n"
        f"export const POLYGLOT_RANDOM = new Uint32Array([\n  {body},\n]);\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}")


def write_eco() -> None:
    table: dict[str, list] = {}
    for letter in "abcde":
        lines = (ROOT / f"data/openings/{letter}.tsv").read_text(encoding="utf-8").splitlines()
        for line in lines[1:]:
            eco, name, pgn = line.split("\t")
            board = chess.Board()
            for token in pgn.split():
                if token.endswith("."):
                    continue
                board.push_san(token)
            key = f"{chess.polyglot.zobrist_hash(board):016x}"
            # Keep the first (canonical) name for transposed positions.
            table.setdefault(key, [eco, name, board.ply()])
    out = ROOT / "public/books/eco.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(table, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(table)} positions)")


def write_vectors() -> None:
    rng = random.Random(1234)
    games = []
    # Classic spec vectors first.
    spec = ["e2e4", "d7d5", "e4e5", "f7f5", "e1e2", "e8f7"]
    games.append({"fen": chess.STARTING_FEN, "moves": spec})
    games.append({"fen": chess.STARTING_FEN, "moves": ["a2a4", "b7b5", "h2h4", "b5b4", "c2c4", "b4c3", "a1a3"]})
    for _ in range(40):
        board = chess.Board()
        moves = []
        for _ in range(rng.randint(10, 80)):
            legal = list(board.legal_moves)
            if not legal:
                break
            move = rng.choice(legal)
            moves.append(move.uci())
            board.push(move)
        games.append({"fen": chess.STARTING_FEN, "moves": moves})
    for g in games:
        board = chess.Board(g["fen"])
        keys = [f"{chess.polyglot.zobrist_hash(board):016x}"]
        for m in g["moves"]:
            board.push_uci(m)
            keys.append(f"{chess.polyglot.zobrist_hash(board):016x}")
        g["keys"] = keys
    out = ROOT / "scripts/polyglot-vectors.json"
    out.write_text(json.dumps(games), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(games)} games)")


if __name__ == "__main__":
    write_random_table()
    write_eco()
    write_vectors()
