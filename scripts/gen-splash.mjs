#!/usr/bin/env node
// Builds the iOS launch screens (apple-touch-startup-image) shown while the
// Home Screen app starts, and rewrites the matching <link> block in index.html.
// Without them iOS shows a blank screen first. Uses the app icon from
// public/icons/icon.svg (run `pnpm icons` first if it changed) and headless
// Chrome for rasterising.
//   node scripts/gen-splash.mjs [path-to-chrome]

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public/splash');
const indexHtml = path.join(root, 'index.html');

// Portrait iPhones that run iOS 16.4+ (the app's minimum): CSS size and pixel ratio.
const DEVICES = [
  [375, 667, 2], //  SE (2nd/3rd gen), 8
  [414, 736, 3], //  8 Plus
  [375, 812, 3], //  X, XS, 11 Pro, 12 mini, 13 mini
  [414, 896, 2], //  XR, 11
  [414, 896, 3], //  XS Max, 11 Pro Max
  [390, 844, 3], //  12, 12 Pro, 13, 13 Pro, 14, 16e
  [428, 926, 3], //  12 Pro Max, 13 Pro Max, 14 Plus
  [393, 852, 3], //  14 Pro, 15, 15 Pro, 16
  [430, 932, 3], //  14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus
  [402, 874, 3], //  16 Pro, 17, 17 Pro
  [420, 912, 3], //  Air
  [440, 956, 3], //  16 Pro Max, 17 Pro Max
];

// Same colour as the app's background (--chrome), so launch blends into the app.
const BACKGROUND = '#050608';

const chrome =
  process.argv[2] ||
  [
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
  ].find((p) => fs.existsSync(p));
if (!chrome) throw new Error('Chrome not found; pass its path as an argument');

const icon = fs.readFileSync(path.join(root, 'public/icons/icon.svg'), 'utf8').replace(
  'width="512" height="512"',
  'width="112" height="112"',
);

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'gml-splash-'));

const links = [];
for (const [w, h, dpr] of DEVICES) {
  const name = `splash-${w * dpr}x${h * dpr}.png`;
  const html = path.join(tmp, `${name}.html`);
  fs.writeFileSync(
    html,
    `<!doctype html><html><body style="margin:0;width:${w}px;height:${h}px;background:${BACKGROUND};` +
      `display:flex;flex-direction:column;align-items:center;justify-content:center;gap:20px;` +
      `font-family:-apple-system,'Segoe UI',system-ui,sans-serif">` +
      `<div style="width:112px;height:112px">${icon}</div>` +
      `<div style="color:#d8dbe6;font-size:19px;font-weight:700;letter-spacing:0.3px">Grandmaster Lab</div>` +
      `</body></html>`,
  );
  execFileSync(
    chrome,
    [
      '--headless=new',
      '--disable-gpu',
      '--hide-scrollbars',
      `--force-device-scale-factor=${dpr}`,
      `--window-size=${w},${h}`,
      `--screenshot=${path.join(outDir, name)}`,
      `file:///${html.replace(/\\/g, '/')}`,
    ],
    { stdio: 'ignore' },
  );
  // PNG IHDR: width and height are big-endian at bytes 16 and 20.
  const png = fs.readFileSync(path.join(outDir, name));
  const size = `${png.readUInt32BE(16)}x${png.readUInt32BE(20)}`;
  if (size !== `${w * dpr}x${h * dpr}`) throw new Error(`${name}: Chrome produced ${size}`);
  console.log('wrote', name, `${Math.round(png.length / 1024)} KB`);
  links.push(
    `    <link rel="apple-touch-startup-image" href="/splash/${name}" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)" />`,
  );
}
fs.rmSync(tmp, { recursive: true, force: true });

const START = '    <!-- splash:start (generated by scripts/gen-splash.mjs) -->';
const END = '    <!-- splash:end -->';
let source = fs.readFileSync(indexHtml, 'utf8');
const block = [START, ...links, END].join('\n');
const from = source.indexOf(START);
const to = source.indexOf(END);
if (from >= 0 && to > from) {
  source = source.slice(0, from) + block + source.slice(to + END.length);
} else {
  source = source.replace('    <link rel="manifest"', `${block}\n    <link rel="manifest"`);
}
fs.writeFileSync(indexHtml, source);
console.log('updated index.html');
